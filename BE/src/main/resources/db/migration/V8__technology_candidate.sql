-- S15P21E102-121. 레지스트리에 없는 의존성을 관리자에게 보여 준다.
--
-- 레지스트리를 손으로 채우면 무엇을 넣어야 하는지 아무도 모른다. 실제 분석이
-- 만나는 것 중 매칭되지 않은 의존성을 세어 두면, 사용자가 많이 쓰는 순서대로
-- 관리자가 등록 여부를 정할 수 있다.
--
-- ---------------------------------------------------------------------------
-- 왜 의존성만인가
--
-- 매칭되지 않은 import는 기술이 아니라 클래스 경로다. org.junit.jupiter.api.Test를
-- 후보로 올려봐야 쓸모가 없고, 패키지로 자르려면 존재하지 않는 깊이가 필요하다 --
-- org.springframework.web은 3세그먼트, org.springframework.data.redis는 4다.
-- 매니페스트 항목은 이미 관리자가 승격할 단위이므로 fact_type 컬럼을 두지 않는다.
--
-- ---------------------------------------------------------------------------
-- 왜 관찰을 따로 남기는가
--
-- 카운터만 증가시키면 되돌릴 방법이 없다. 같은 분석이 두 번 반영됐는지, 분석이
-- 삭제되면 무엇을 빼야 하는지 알 수 없고, 집계가 한 번 틀어지면 진짜 값을
-- 복원할 수 없다. 관찰 행이 남아 있으면 카운트는 언제든 다시 계산된다.
--
-- 정렬 기준이 사용자 수인 것도 여기서 나온다. 관리자가 답해야 할 질문은 "몇
-- 줄인가"가 아니라 "몇 명에게 영향이 있는가"다. occurrence 수로 세면 모노레포
-- 하나가 순위를 지배한다.
-- ---------------------------------------------------------------------------

CREATE TABLE "technology_candidate" (
    "candidate_id"              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    -- DEPENDENCY fact의 생태계. IMPORT_PATH 쪽 값(JAVA, PYTHON...)은 오지 않는다.
    "ecosystem"                 VARCHAR(24)  NOT NULL,
    -- 버전을 뗀 좌표. 안 떼면 릴리스마다 새 후보로 갈라진다.
    "coordinate"                VARCHAR(300) NOT NULL,
    -- 모든 선언이 일치할 때만 값이 있다. 갈리면 NULL -- 한 모듈에서 프로덕션이고
    -- 다른 모듈에서 테스트 전용인 라이브러리는 단일한 답이 없다.
    "scope"                     VARCHAR(40),
    "distinct_user_count"       INTEGER      NOT NULL DEFAULT 0,
    "distinct_repository_count" INTEGER      NOT NULL DEFAULT 0,
    "occurrence_count"          INTEGER      NOT NULL DEFAULT 0,
    "first_seen_at"             TIMESTAMPTZ  NOT NULL,
    "last_seen_at"              TIMESTAMPTZ  NOT NULL,
    -- NEW      아직 아무도 보지 않았다
    -- REVIEWING 관리자가 검토 중
    -- PROMOTED  Registry에 등록됐다. promoted_tech_id가 어느 기술인지 말한다
    -- REJECTED  등록하지 않기로 했다. 계속 세되 기본 목록에서 감춘다 --
    --           거부한 것이 매주 다시 1위로 올라오면 화면이 무용지물이 된다
    "status"                    VARCHAR(16)  NOT NULL DEFAULT 'NEW',
    "promoted_tech_id"          VARCHAR(80),
    "decided_by"                BIGINT,
    "decided_at"                TIMESTAMPTZ,
    "decision_note"             TEXT
);

ALTER TABLE "technology_candidate"
    ADD CONSTRAINT "PK_TECHNOLOGY_CANDIDATE" PRIMARY KEY ("candidate_id");

-- 같은 좌표는 하나의 후보다. scope는 키가 아니다: spring-petclinic은 pom.xml과
-- build.gradle을 둘 다 갖고 있어 h2가 한쪽은 runtime, 다른 쪽은 runtimeOnly다.
-- scope를 키에 넣으면 후보가 둘로 갈라져 관리자 화면이 반쪽짜리 둘을 세운다.
ALTER TABLE "technology_candidate"
    ADD CONSTRAINT "UQ_TECHNOLOGY_CANDIDATE" UNIQUE ("ecosystem", "coordinate");

ALTER TABLE "technology_candidate"
    ADD CONSTRAINT "CK_TECHNOLOGY_CANDIDATE_ECOSYSTEM"
        CHECK ("ecosystem" IN ('MAVEN', 'NPM', 'PYPI', 'NUGET')),
    ADD CONSTRAINT "CK_TECHNOLOGY_CANDIDATE_STATUS"
        CHECK ("status" IN ('NEW', 'REVIEWING', 'PROMOTED', 'REJECTED')),
    -- 승격은 기술을 지목해야 한다. 승격했다면서 어느 기술인지 없으면 그 결정을
    -- 나중에 되짚을 수 없다.
    ADD CONSTRAINT "CK_TECHNOLOGY_CANDIDATE_PROMOTED"
        CHECK (("status" = 'PROMOTED') = ("promoted_tech_id" IS NOT NULL)),
    ADD CONSTRAINT "CK_TECHNOLOGY_CANDIDATE_DECIDED"
        CHECK (("status" IN ('PROMOTED', 'REJECTED')) = ("decided_at" IS NOT NULL));

-- 관리자 화면의 기본 정렬. 부분 인덱스인 이유는 거부된 것을 기본 목록에서
-- 빼기 때문이다.
CREATE INDEX "idx_technology_candidate_ranking"
    ON "technology_candidate" ("distinct_user_count" DESC, "distinct_repository_count" DESC)
    WHERE "status" <> 'REJECTED';

CREATE INDEX "idx_technology_candidate_status"
    ON "technology_candidate" ("status", "last_seen_at" DESC);

-- ---------------------------------------------------------------------------
-- 관찰. 카운트의 원본이다.
-- ---------------------------------------------------------------------------
CREATE TABLE "technology_candidate_observation" (
    "observation_id"    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    "candidate_id"      BIGINT       NOT NULL,
    "analysis_id"       VARCHAR(80)  NOT NULL,
    "user_id"           BIGINT       NOT NULL,
    "repository_id"     VARCHAR(80)  NOT NULL,
    "scope"             VARCHAR(40),
    "occurrence_count"  INTEGER      NOT NULL CHECK ("occurrence_count" >= 1),
    "observed_at"       TIMESTAMPTZ  NOT NULL
);

ALTER TABLE "technology_candidate_observation"
    ADD CONSTRAINT "PK_TECHNOLOGY_CANDIDATE_OBSERVATION" PRIMARY KEY ("observation_id");

-- 한 분석은 한 후보를 한 번만 관찰한다. 결과 이벤트는 at-least-once이고,
-- analysis_job의 상태가 1차 방어선이지만 이 제약이 그것과 독립적으로 막는다.
ALTER TABLE "technology_candidate_observation"
    ADD CONSTRAINT "UQ_CANDIDATE_OBSERVATION" UNIQUE ("candidate_id", "analysis_id");

ALTER TABLE "technology_candidate_observation"
    ADD CONSTRAINT "FK_CANDIDATE_OBSERVATION_CANDIDATE" FOREIGN KEY ("candidate_id")
        REFERENCES "technology_candidate" ("candidate_id"),
    ADD CONSTRAINT "FK_CANDIDATE_OBSERVATION_JOB" FOREIGN KEY ("analysis_id")
        REFERENCES "analysis_job" ("analysis_id"),
    ADD CONSTRAINT "FK_CANDIDATE_OBSERVATION_USER" FOREIGN KEY ("user_id")
        REFERENCES "user" ("user_id");

-- 집계를 다시 계산할 때 후보별로 모아 읽는다.
CREATE INDEX "idx_candidate_observation_candidate"
    ON "technology_candidate_observation" ("candidate_id");

-- 분석 하나가 남긴 관찰을 되짚거나 취소할 때.
CREATE INDEX "idx_candidate_observation_analysis"
    ON "technology_candidate_observation" ("analysis_id");
