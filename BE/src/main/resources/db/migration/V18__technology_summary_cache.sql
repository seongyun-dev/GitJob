-- 기술 요약을 저장한다. 같은 입력에 GPU 를 두 번 태우지 않기 위해서다.
--
-- 요약 서비스는 캐시를 하지 않는다. 같은 Fact Pack 을 두 번 보내면 두 번 다
-- 추론이 돌고 같은 시간이 걸린다(실측 4.4초 / 3.9초). 응답이 cache_key 를 주는
-- 것이 곧 "저장은 부르는 쪽 몫"이라는 뜻이고, AI/llm/cache.py 주석도 그렇게
-- 적고 있다 -- Redis 가 아니라 이 테이블이어야 하는 이유는, 재시작으로 비면
-- 화면 진입 때 기술 열두 개를 한꺼번에 다시 만들게 되고 노트북 GPU 에서 그것은
-- 수십 초의 빈 카드이기 때문이다.
--
-- ---------------------------------------------------------------------------
-- 왜 사용자·기술마다 한 행인가
--
-- 입력이 바뀌면 옛 요약은 쓸 데가 없다. 해시를 키에 넣어 이력을 쌓으면 레벨이
-- 오를 때마다 행이 늘고 아무도 지우지 않는다. 한 행을 덮어쓰면 테이블 크기가
-- 사용자 수 x 기술 수로 묶인다.
--
-- ---------------------------------------------------------------------------
-- 왜 우리가 만든 해시로 조회하는가
--
-- 응답의 cache_key 는 요약 서비스가 자기 방식으로 직렬화한 Fact Pack 의
-- sha256 이다. 그 바이트를 Java 에서 그대로 재현하려면 키 순서와 구분자까지
-- 맞춰야 하고, 한쪽이 바뀌면 조용히 어긋난다. 그래서 조회는 우리가 만든
-- fact_pack_sha256 로 하고, 저쪽 키는 추적용으로만 남긴다.

CREATE TABLE "technology_summary" (
    "technology_summary_id" BIGINT GENERATED BY DEFAULT AS IDENTITY,
    "user_id"               BIGINT       NOT NULL,
    "tech_id"               VARCHAR(80)  NOT NULL,

    -- 우리가 보낸 Fact Pack 의 해시. 레벨이나 근거가 바뀌면 값이 달라져
    -- 자동으로 다시 만들어진다.
    "fact_pack_sha256"      CHAR(64)     NOT NULL,

    -- 요약 서비스가 계산한 키. 조회에 쓰지 않는다.
    "cache_key"             CHAR(64),

    -- 프롬프트가 바뀌면 옛 문구의 요약이 남으면 안 된다. 저장된 값이 지금
    -- /health 가 말하는 값과 다르면 미스로 취급한다.
    "prompt_version"        VARCHAR(80)  NOT NULL,
    "model"                 VARCHAR(80)  NOT NULL,

    -- OK       모델이 쓴 문장
    -- FALLBACK 데이터에서 기계적으로 만든 문장. 오류가 아니며 화면은 구분하지
    --          않는다 -- 카드는 요약 없이도 완성돼 있고 이것은 그 위에 얹는다
    "llm_status"            VARCHAR(16)  NOT NULL,

    "headline"              TEXT         NOT NULL,
    "summary"               TEXT         NOT NULL,
    -- 다음 수준까지 무엇이 비었는지. next_level 이 없으면 NULL 이다.
    "gap"                   TEXT,
    "confidence"            VARCHAR(8)   NOT NULL,
    -- 어느 근거로 쓴 문장인지. 화면에 보여주지 않고 되짚을 때만 쓴다.
    "used_highlights"       INTEGER[]    NOT NULL DEFAULT '{}',

    "generated_at"          TIMESTAMPTZ  NOT NULL
);

ALTER TABLE "technology_summary"
    ADD CONSTRAINT "PK_TECHNOLOGY_SUMMARY" PRIMARY KEY ("technology_summary_id");

-- 사용자 한 명의 기술 하나에 요약은 하나다. 조회이자 UPSERT 의 충돌 대상이다.
ALTER TABLE "technology_summary"
    ADD CONSTRAINT "UQ_TECHNOLOGY_SUMMARY" UNIQUE ("user_id", "tech_id");

ALTER TABLE "technology_summary"
    ADD CONSTRAINT "CK_TECHNOLOGY_SUMMARY_STATUS"
        CHECK ("llm_status" IN ('OK', 'FALLBACK')),
    ADD CONSTRAINT "CK_TECHNOLOGY_SUMMARY_CONFIDENCE"
        CHECK ("confidence" IN ('HIGH', 'MEDIUM', 'LOW'));

ALTER TABLE "technology_summary"
    ADD CONSTRAINT "FK_TECHNOLOGY_SUMMARY_USER" FOREIGN KEY ("user_id")
        REFERENCES "user" ("user_id");

COMMENT ON COLUMN "technology_summary"."fact_pack_sha256" IS
    '우리가 보낸 Fact Pack 의 해시. 조회 키이며, 저장된 값과 다르면 다시 만든다.';
COMMENT ON COLUMN "technology_summary"."cache_key" IS
    '요약 서비스가 계산한 키. 추적용이며 조회에 쓰지 않는다.';
COMMENT ON COLUMN "technology_summary"."llm_status" IS
    'FALLBACK 은 실패가 아니다. 데이터에서 만든 문장이며 화면은 OK 와 구분하지 않는다.';
